"""Writes lib/firebase_options.dart from android-config/google-services.json."""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "android-config" / "google-services.json"
pkg = "in.appbucket.baatcheet"

placeholder = True
opts = dict(apiKey="none", appId="1:0:android:0", messagingSenderId="0", projectId="baatcheet-placeholder", storageBucket="")
if src.exists():
    g = json.loads(src.read_text())
    pid = g["project_info"]["project_id"]
    if pid != "baatcheet-placeholder":
        client = next(
            (c for c in g["client"] if c["client_info"]["android_client_info"]["package_name"] == pkg),
            None,
        )
        if client is None:
            raise SystemExit(f"google-services.json has no Android app with package name {pkg}")
        placeholder = False
        opts = dict(
            apiKey=client["api_key"][0]["current_key"],
            appId=client["client_info"]["mobilesdk_app_id"],
            messagingSenderId=g["project_info"]["project_number"],
            projectId=pid,
            storageBucket=g["project_info"].get("storage_bucket", ""),
        )

body = "\n".join(f"    {k}: '{v}'," for k, v in opts.items())
(root / "lib" / "firebase_options.dart").write_text(f"""// Generated by tool/gen_firebase_options.py. Do not edit.
import 'package:firebase_core/firebase_core.dart';

class FirebaseConfig {{
  static const bool isPlaceholder = {str(placeholder).lower()};
  static const FirebaseOptions options = FirebaseOptions(
{body}
  );
}}
""")
print("firebase_options.dart written; placeholder =", placeholder)
